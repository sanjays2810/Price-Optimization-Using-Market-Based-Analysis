"""Report builders (PDF via reportlab, Excel via openpyxl)."""
import datetime as dt
from pathlib import Path

import pandas as pd

from app.config import APP_NAME, REPORT_DIR
from app.ml import predictor
from app.services import analytics as an
from app.services import optimizer

REPORT_TYPES = {
    "dataset_analysis": "Dataset Analysis Report",
    "market_trend": "Market Trend Report",
    "price_prediction": "Future Price Prediction Report",
    "price_optimization": "Price Optimization Report",
    "demand_supply": "Demand and Supply Report",
    "profit_analysis": "Profit Analysis Report",
}
CUR = "Rs."


def _r(df, n=2):
    return df.round(n) if isinstance(df, pd.DataFrame) else df


def build(rtype, df, ds, report, product_id=None, algorithm="linear_regression", horizon=30):
    secs = []
    title = REPORT_TYPES[rtype]
    sub = f"Dataset: {ds.name} ({ds.source}) | {df.date.min():%d %b %Y} to {df.date.max():%d %b %Y} | {df.product_id.nunique()} products"
    if ds.source == "sample":
        secs.append({"heading": "Data notice", "paragraphs": ["This report uses SIMULATED sample data generated by the application. It is not real market data."]})

    if rtype == "dataset_analysis":
        rows = [(k.replace("_", " ").title(), str(v)) for k, v in report.items()
                if k in ("rows_raw", "rows_clean", "products", "categories", "date_min", "date_max", "duplicates_removed", "invalid_dates_removed", "invalid_values_set_missing", "status")]
        secs.append({"heading": "Validation summary", "df": pd.DataFrame(rows, columns=["Item", "Value"])})
        mb = report.get("missing_before", {})
        secs.append({"heading": "Missing values before cleaning", "df": pd.DataFrame({"Column": list(mb), "Missing": list(mb.values())})})
        notes = report.get("warnings", []) + report.get("assumptions", [])
        if notes:
            secs.append({"heading": "Warnings and assumptions", "paragraphs": notes})
        e = an.eda(df)
        secs.append({"heading": "Descriptive statistics", "df": _r(pd.DataFrame(e["descriptive"])[["column", "count", "mean", "median", "std", "min", "max"]])})
        secs.append({"heading": "Category comparison", "df": _r(pd.DataFrame(e["categories"]))})
        secs.append({"heading": "Outlier detection (IQR within product)", "df": _r(pd.DataFrame(e["outliers"]))})

    elif rtype == "market_trend":
        t = an.trends(df, product_id)
        tab = pd.DataFrame(t["products"])[["product_name", "category", "last_price", "change_7d", "change_30d", "change_90d", "trend_label", "volatility", "seasonal"]]
        secs.append({"heading": "Trend summary", "paragraphs": [f"Bullish: {t['counts']['increasing']}, Bearish: {t['counts']['decreasing']}, Stable: {t['counts']['stable']}. Change columns are % vs the previous period."],
                     "df": _r(tab)})
        if t["selected"]:
            s = t["selected"]
            secs.append({"heading": f"Why {s['product_name']} is moving", "paragraphs": s["explanation"]})
            secs.append({"heading": "Monthly price movement", "df": _r(pd.DataFrame(s["periods"]["monthly"]))})
            secs.append({"heading": "Quarterly price movement", "df": _r(pd.DataFrame(s["periods"]["quarterly"]))})

    elif rtype == "price_prediction":
        secs.append({"heading": "Disclaimer", "paragraphs": [predictor.DISCLAIMER]})
        if product_id:
            g = df[df.product_id == int(product_id)]
            r = predictor.run_forecast(an.daily(g, "historical_price"), algorithm, horizon)
            sm = r["summary"]
            secs.append({"heading": f"{g.product_name.iloc[0]}: {r['algorithm_label']}, {horizon} days", "paragraphs": [
                f"Last observed price: {r['last_value']:.2f}. Predicted at end of period: {sm['predicted_final']:.2f} ({sm['change_pct']:+.1f}%, {sm['direction']}).",
                f"Train/test split: {r['split']['method']}; train {r['split']['train_size']} days, test {r['split']['test_size']} days."] + r["notes"]})
            secs.append({"heading": "Model evaluation (test period)", "df": _r(pd.DataFrame([r["metrics"]]), 4)})
            fc = pd.DataFrame(r["forecast"])
            fc["date"] = fc["date"].dt.strftime("%Y-%m-%d")
            secs.append({"heading": "Forecast", "df": _r(fc)})
        else:
            rows = []
            for pid, g in df.groupby("product_id"):
                try:
                    s = an.daily(g, "historical_price")
                    f = predictor.quick_forecast(s, horizon)
                    rows.append({"Product": g.product_name.iloc[0], "Category": g.category.iloc[0], "Last price": s.iloc[-1],
                                 f"Predicted ({horizon}d)": f[-1], "Change %": (f[-1] / s.iloc[-1] - 1) * 100})
                except Exception:
                    pass
            secs.append({"heading": f"All products: linear trend + seasonality, {horizon} days", "df": _r(pd.DataFrame(rows))})

    elif rtype == "price_optimization":
        secs.append({"heading": "Method", "paragraphs": ["Model-based rows maximise expected profit under a fitted elasticity model within safe bounds; heuristic rows are rule-based and not claimed optimal. Prices never fall below cost plus minimum margin."]})
        ids = [int(product_id)] if product_id else sorted(df.product_id.unique())
        rows = []
        for pid in ids:
            try:
                o = optimizer.optimize(df, pid, {})
            except Exception:
                continue
            R, C = o["recommended"], o["current"]
            rows.append({"Product": o["product"]["name"], "Mode": o["mode"], f"Current price ({CUR})": C["price"],
                         "Recommended": R["best_price"], "Min profitable": R["minimum_profitable_price"], "Max suggested": R["maximum_suggested_price"],
                         "Change %": R["price_change_pct"], "Exp. profit (30d)": R["expected_profit"], "Strategy": R["strategy"].split(":")[0]})
        secs.append({"heading": "Recommendations", "df": _r(pd.DataFrame(rows))})

    elif rtype == "demand_supply":
        d = an.demand_supply(df, product_id)
        secs.append({"heading": "Market situations", "paragraphs": [f"{k}: {v} product(s)" for k, v in d["situation_counts"].items()] + [d["rules"]]})
        secs.append({"heading": "Product demand and supply", "df": _r(pd.DataFrame(d["products"]).drop(columns=["product_id"]))})

    elif rtype == "profit_analysis":
        p = an.profit(df, product_id)
        t = p["totals"]
        secs.append({"heading": "Totals", "paragraphs": [f"Revenue {CUR} {t['revenue']:,.0f} | Cost {CUR} {t['cost']:,.0f} | Profit {CUR} {t['profit']:,.0f} | Margin {t['margin_pct']:.1f}%", p["formulas"]]})
        secs.append({"heading": "Annual", "df": _r(p["annual"])})
        secs.append({"heading": "Category-wise", "df": _r(p["categories"])})
        secs.append({"heading": "Product-wise", "df": _r(p["products"])})
        secs.append({"heading": "Monthly", "df": _r(p["monthly"])})
        if p["forecast"]:
            f = p["forecast"]
            secs.append({"heading": "Next 30-day forecast", "paragraphs": [f"Forecast revenue {CUR} {f['revenue_total_30d']:,.0f}; forecast profit {CUR} {f['profit_total_30d']:,.0f} (estimates, not guarantees)."]})
    return {"title": title, "subtitle": sub, "sections": secs}


def _fmt(v):
    if isinstance(v, float):
        return f"{v:,.2f}"
    return str(v)


def write_pdf(rep, path: Path):
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
    st = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=st["Title"], textColor=colors.HexColor("#0b1f44"), fontSize=20, alignment=0)
    h2 = ParagraphStyle("h2", parent=st["Heading2"], textColor=colors.HexColor("#2f5bea"), fontSize=12, spaceBefore=10)
    body = ParagraphStyle("b", parent=st["BodyText"], fontSize=9, leading=12)
    cell = ParagraphStyle("c", parent=body, fontSize=7, leading=8.5)
    doc = SimpleDocTemplate(str(path), pagesize=landscape(A4), leftMargin=12 * mm, rightMargin=12 * mm, topMargin=12 * mm, bottomMargin=12 * mm, title=rep["title"])
    el = [Paragraph(rep["title"], h1), Paragraph(APP_NAME, body), Paragraph(rep["subtitle"], body),
          Paragraph(f"Generated {dt.datetime.now():%d %b %Y %H:%M}", body), Spacer(1, 6)]
    for s in rep["sections"]:
        el.append(Paragraph(s["heading"], h2))
        for ptxt in s.get("paragraphs", []):
            el.append(Paragraph(str(ptxt).replace("&", "&amp;").replace("<", "&lt;"), body))
        df = s.get("df")
        if df is not None and len(df):
            note = f"Showing first 40 of {len(df)} rows." if len(df) > 40 else None
            d = df.head(40)
            data = [[Paragraph(f"<b>{str(c)[:22]}</b>", cell) for c in d.columns]]
            for row in d.itertuples(index=False):
                data.append([Paragraph(_fmt(v)[:48].replace("&", "&amp;").replace("<", "&lt;"), cell) for v in row])
            tb = Table(data, repeatRows=1)
            tb.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#dfe7fb")),
                                    ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#c8d0e0")),
                                    ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f6f8fc")]),
                                    ("VALIGN", (0, 0), (-1, -1), "TOP")]))
            el += [Spacer(1, 3), tb]
            if note:
                el.append(Paragraph(note, body))
    doc.build(el)


def write_xlsx(rep, path: Path):
    from openpyxl.styles import Font, PatternFill
    with pd.ExcelWriter(path, engine="openpyxl") as xw:
        lines = [rep["title"], APP_NAME, rep["subtitle"], f"Generated {dt.datetime.now():%d %b %Y %H:%M}", ""]
        for s in rep["sections"]:
            lines.append(s["heading"])
            lines += [str(p) for p in s.get("paragraphs", [])]
        pd.DataFrame({"Report": lines}).to_excel(xw, sheet_name="Summary", index=False)
        for i, s in enumerate(rep["sections"], 1):
            if s.get("df") is not None and len(s["df"]):
                name = f"{i}_{s['heading']}"[:31].replace("/", "-").replace(":", "-")
                s["df"].to_excel(xw, sheet_name=name, index=False)
        for ws in xw.book.worksheets:
            for c in ws[1]:
                c.font = Font(bold=True, color="FFFFFF")
                c.fill = PatternFill("solid", fgColor="0B1F44")
            for col in ws.columns:
                ws.column_dimensions[col[0].column_letter].width = min(max(len(str(c.value or "")) for c in col[:50]) + 2, 70)


def generate(rtype, fmt, df, ds, report, **kw) -> Path:
    rep = build(rtype, df, ds, report, **kw)
    name = f"{rtype}_{dt.datetime.now():%Y%m%d_%H%M%S}.{fmt}"
    path = REPORT_DIR / name
    (write_pdf if fmt == "pdf" else write_xlsx)(rep, path)
    return path
